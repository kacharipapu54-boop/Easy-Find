function loadURLFilters() {

    if (!searchInput) {

        return;

    }


    const params =
        new URLSearchParams(
            window.location.search
        );


    const location =
        params.get("location");


    const type =
        params.get("type");


    if (location) {

        searchInput.value =
            location;

    }


    if (
        type === "PG" ||
        type === "Room"
    ) {

        selectedPropertyType =
            type;

        propertyTypeButtons
            .forEach(button => {

                button.classList.remove(
                    "active"
                );


                if (
                    button.dataset
                        .propertyType ===
                    type
                ) {

                    button.classList.add(
                        "active"
                    );

                }

            });

    }

    if (
        type === "Rental Room"
    ) {

        selectedPropertyType =
            type;


        propertyTypeButtons
            .forEach(button => {

                button.classList.remove(
                    "active"
                );


                if (
                    button.dataset
                        .propertyType ===
                    type
                ) {

                    button.classList.add(
                        "active"
                    );

                }

            });

    }


    displayProperties();

}


function initializeMap() {

    const mapElement =
        document.getElementById(
            "map"
        );


    if (!mapElement) {

        return;

    }


    if (
        typeof L ===
        "undefined"
    ) {

        console.log(
            "Leaflet not loaded."
        );

        return;

    }


    /*
       Initial map center.

       This is only a general Golaghat-area
       starting point, not an exact property
       location.
    */

    map =
        L.map("map").setView(
            [26.5239, 93.9630],
            12
        );


    L.tileLayer(
        "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png",
        {

            attribution:
                "&copy; OpenStreetMap contributors"

        }
    ).addTo(map);


    updateMap(properties);

}


function updateMap(propertyList) {

    if (!map) {

        return;

    }




    map.eachLayer(layer => {

        if (
            layer instanceof
            L.Marker
        ) {

            map.removeLayer(layer);

        }

    });


    const validProperties =
        propertyList.filter(
            property =>
                property.latitude !==
                null &&
                property.longitude !==
                null
        );


    validProperties.forEach(
        property => {

            const marker =
                L.marker([
                    property.latitude,
                    property.longitude
                ])
                .addTo(map);


            marker.bindPopup(`

                <strong>
                    ${escapeHTML(
                        property.name
                    )}
                </strong>

                <br>

                ${escapeHTML(
                    property.address
                )}

            `);

        }
    );

}


