function displayProperties() {

    if (!propertyContainer) {

        return;

    }


    const search =
        searchInput
            ? searchInput.value
                .toLowerCase()
                .trim()
            : "";


    const filtered =
        properties.filter(
            property => {


                const genderMatch =

                    selectedGender ===
                    "All" ||

                    property.gender ===
                    selectedGender ||

                    property.gender ===
                    "All";


                const typeMatch =

                    selectedPropertyType ===
                    "All" ||

                    property.type ===
                    selectedPropertyType;


                const searchable =

                    `${property.name}
                    ${property.address}
                    ${property.type}
                    ${property.gender}`
                        .toLowerCase();


                const searchMatch =

                    search === "" ||

                    searchable.includes(
                        search
                    );


                return (

                    genderMatch &&
                    typeMatch &&
                    searchMatch

                );

            }
        );


    propertyContainer.innerHTML =
        "";


    const resultCount =
        document.getElementById(
            "resultCount"
        );


    if (resultCount) {

        resultCount.textContent =
            `${filtered.length} ${
                filtered.length === 1
                    ? "place"
                    : "places"
            } found`;

    }



    if (filtered.length === 0) {

        propertyContainer.innerHTML = `

            <div class="no-results">

                <div
                    class="no-results-icon"
                    style="font-size:50px;"
                >
                    🔍
                </div>

                <h2>
                    No places found
                </h2>

                <p>
                    Try another location
                    or change your filters.
                </p>

            </div>

        `;

        return;

    }



    filtered.forEach(
        (property,index) => {


            const card =
                document.createElement(
                    "article"
                );


            card.className =
                "property-card";


            card.style.animationDelay =
                `${index * 0.08}s`;


            let genderLabel;


            if (
                property.gender ===
                "Boys"
            ) {

                genderLabel = `
                    <i data-lucide="user"></i>
                    Boys
                `;

            }

            else if (
                property.gender ===
                "Girls"
            ) {

                genderLabel = `
                    <i data-lucide="user"></i>
                    Girls
                `;

            }

            else {

                genderLabel = `
                    <i data-lucide="users"></i>
                    All
                `;

            }


            const icon =

                property.type ===
                "PG"

                    ? "house"

                    : "door-open";


            card.innerHTML = `

                <div
                    class="property-image"
                >

                    <i
                        data-lucide="${icon}"
                    ></i>

                </div>


                <div
                    class="property-content"
                >

                    <span class="badge">

                        ${genderLabel}

                    </span>


                    <h2>

                        ${escapeHTML(
                            property.name
                        )}

                    </h2>


                    <p
                        class="property-address"
                    >

                        <i data-lucide="map-pin"></i>

                        ${escapeHTML(
                            property.address
                        )}

                    </p>


                    <a
                        class="view-btn"
                        href="details.html?id=${property.id}"
                    >

                        View Details

                        <span>→</span>

                    </a>

                </div>

            `;


            propertyContainer
                .appendChild(card);

        }
    );


    /* Refresh icons */

    if (
        typeof lucide !==
        "undefined"
    ) {

        lucide.createIcons();

    }


    /* Refresh map */

    updateMap(filtered);

}


