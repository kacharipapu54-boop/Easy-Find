function initializeDetailsMap(
    property
) {

    const mapElement =
        document.getElementById(
            "detailsMap"
        );


    if (!mapElement) {

        return;

    }


    if (
        typeof L ===
        "undefined"
    ) {

        return;

    }


    /*
       We only create an exact marker when
       verified coordinates are available.
    */

    if (
        property.latitude === null ||
        property.longitude === null
    ) {

        mapElement.innerHTML = `

            <div
                style="
                    height:100%;
                    display:flex;
                    align-items:center;
                    justify-content:center;
                    text-align:center;
                    padding:30px;
                    color:#667978;
                    background:#0b1919;
                "
            >

                📍 Exact coordinates have not
                been added for this property yet.

            </div>

        `;

        return;

    }


    const detailMap =
        L.map(
            "detailsMap"
        ).setView(
            [
                property.latitude,
                property.longitude
            ],
            16
        );


    L.tileLayer(
        "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png",
        {

            attribution:
                "&copy; OpenStreetMap contributors"

        }
    ).addTo(detailMap);


    L.marker([
        property.latitude,
        property.longitude
    ])
    .addTo(detailMap)
    .bindPopup(
        `<strong>${escapeHTML(
            property.name
        )}</strong>`
    )
    .openPopup();

}



function escapeHTML(value) {

    return String(value)

        .replace(
            /&/g,
            "&amp;"
        )

        .replace(
            /</g,
            "&lt;"
        )

        .replace(
            />/g,
            "&gt;"
        )

        .replace(
            /"/g,
            "&quot;"
        )

        .replace(
            /'/g,
            "&#039;"
        );

}



